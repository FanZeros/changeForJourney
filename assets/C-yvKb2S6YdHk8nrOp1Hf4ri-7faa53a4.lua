--- 基于开服时间生成带日期的公告列表
--- @param serverOpenTime number 开服时间戳（os.time 格式），0 则取当前时间
--- @return table[] 附带 date 字段的公告副本列表
function AnnouncementConfig.buildWithDates(serverOpenTime)
    local baseTime = (serverOpenTime and serverOpenTime > 0) and serverOpenTime or os.time()
    local result = {}
    for _, ann in ipairs(AnnouncementConfig.ANNOUNCEMENTS) do
        local copy = {}
        ---@diagnostic disable-next-line: assign-type-mismatch
        for k, v in pairs(ann) do copy[k] = v end
        local offsetSec = (ann.dateOffset or 0) * 86400
        copy.date = os.date("%Y/%m/%d", baseTime + offsetSec)
        result[#result + 1] = copy
    end
    return result
end

return AnnouncementConfig
