---@type number[]|nil
local sortedIds = nil

local function ensureSortedIds()
    if sortedIds then return end
    sortedIds = {}
    for sid in pairs(IdleIncomeConfig.STAGES) do
        sortedIds[#sortedIds + 1] = sid
    end
    table.sort(sortedIds)
end

--- 获取关卡挂机收益（缺失关卡回退到 <= stageId 的最近已配置关卡）
---@param stageId number
---@return number gold, number exp
function IdleIncomeConfig.get(stageId)
    local cfg = IdleIncomeConfig.STAGES[stageId]
    if cfg then return cfg.gold, cfg.exp end

    ensureSortedIds()
    local lo, hi, best = 1, #sortedIds, nil
    while lo <= hi do
        local mid = (lo + hi) // 2
        local sid = sortedIds[mid]
        if sid <= stageId then
            best = sid
            lo = mid + 1
        else
            hi = mid - 1
        end
    end
    if best then
        local c = IdleIncomeConfig.STAGES[best]
        return c.gold, c.exp
    end
    return 0, 0
end

return IdleIncomeConfig
