--- 获取指定英雄在指定触发类型下的台词
---@param heroId number
---@param triggerType string  "entry"|"crit"|"kill"|"death"|"victory"
---@return string|nil
function DialogueConfig.get(heroId, triggerType)
    local hero = DialogueConfig.LINES[heroId]
    if not hero then return nil end
    local line = hero[triggerType]
    if type(line) == "table" then
        -- 数组时随机选取
        return line[math.random(#line)]
    end
    return line
end

return DialogueConfig
