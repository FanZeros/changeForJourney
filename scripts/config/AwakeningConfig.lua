--- 获取指定角色的觉醒配置
---@param heroId number 英雄 ID (1~15, 16, 20~23)
---@return string[]|nil 7个觉醒效果描述，索引1~7
function AC.get(heroId)
    return AC.DATA[heroId]
end

--- 获取指定角色指定觉醒节点的效果描述
---@param heroId number
---@param nodeIndex number 1~7
---@return string|nil
function AC.getNodeEffect(heroId, nodeIndex)
    local data = AC.DATA[heroId]
    if data then
        return data[nodeIndex]
    end
    return nil
end

-- ======================== 觉醒碎片消耗 ========================
-- 每个觉醒节点消耗的英雄碎片数量（索引 1~7 对应节点 1~7）
AC.SHARD_COST = { 10, 20, 30, 40, 50, 60, 70 }

--- 获取指定节点的碎片消耗
---@param nodeIndex number 1~7
---@return number
function AC.getShardCost(nodeIndex)
    return AC.SHARD_COST[nodeIndex] or 0
end

--- 获取全部觉醒节点的碎片总消耗
---@return number
function AC.getTotalShardCost()
    local total = 0
    for _, cost in ipairs(AC.SHARD_COST) do
        total = total + cost
    end
    return total
end

-- ======================== 觉醒节点战力值 ========================
-- 按品质等级定义每个觉醒节点的固定战力加成
-- quality: 1=R, 2=SR, 3=SSR
AC.COMBAT_POWER = {
    [1] = { 5,  5,  8,  8, 10, 12, 20 },  -- R   合计68
    [2] = { 8,  8, 12, 12, 15, 18, 30 },  -- SR  合计103
    [3] = { 12, 12, 18, 18, 22, 25, 40 }, -- SSR 合计147
    [4] = { 15, 15, 22, 22, 28, 32, 50 }, -- UR  合计184
}

--- 计算指定角色已点亮觉醒节点的总战力
---@param heroId number 英雄ID (1~15, 16, 20~23)
---@param awakening number[] 觉醒状态数组，awakening[i]=1表示节点i已点亮
---@return number 觉醒总战力
function AC.calcTotalCombatPower(heroId, awakening)
    if not awakening then return 0 end
    local HeroConfig = require("config.HeroConfig")
    local hero = HeroConfig.get(heroId)
    if not hero then return 0 end
    local powerTable = AC.COMBAT_POWER[hero.quality]
    if not powerTable then return 0 end
    local total = 0
    for i = 1, #powerTable do
        if awakening[i] then  -- 兼容 boolean true（新存档）和数字 1（旧存档）
            total = total + powerTable[i]
        end
    end
    return total
end

return AC
