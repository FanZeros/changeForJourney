-- ======================== 匹配辅助 ========================

--- 按长度降序排好的关键词列表（长词优先匹配，避免 "回响客" 被 "回响" 截胡）
---@type string[]
KW.SORTED_KEYS = nil

local function buildSorted()
    local keys = {}
    for k in pairs(KW.KEYWORDS) do
        keys[#keys + 1] = k
    end
    table.sort(keys, function(a, b)
        local la, lb = #a, #b
        if la ~= lb then return la > lb end
        return a < b
    end)
    KW.SORTED_KEYS = keys
end

--- 获取关键词定义
---@param name string
---@return KeywordDef|nil
function KW.get(name)
    return KW.KEYWORDS[name]
end

--- 获取按长度降序排序的关键词数组（惰性构建并缓存）
---@return string[]
function KW.sortedKeys()
    if not KW.SORTED_KEYS then buildSorted() end
    ---@type string[]
    local keys = KW.SORTED_KEYS
    return keys
end

return KW
