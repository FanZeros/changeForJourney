--- 查询关卡推荐战力（官方口径）
---@param stageId number
---@return number|nil recommendPower
---@return boolean|nil extrapolated
function SRP.get(stageId)
    local entry = SRP.byStage[stageId]
    if not entry then return nil, nil end
    return entry.p, entry.x or false
end

--- 查询关卡推荐战力（分项预估口径）
---@param stageId number
---@return number|nil recommendEstimate
function SRP.getEstimate(stageId)
    local entry = SRP.byStage[stageId]
    return entry and entry.e or nil
end

